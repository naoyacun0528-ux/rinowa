const ctx = yosegi.makeContext(CONVERSATION, MEMBERS, STICKERS);

const out = {
  note: 'Generated by research/wire/vectors.js. Any implementation of Yosegi v1 must produce '
    + 'and read these exactly. See docs/YOSEGI_V1_SPEC.md. Do not edit by hand.',
  version: 1,
  conversationId: CONVERSATION,
  memberIds: MEMBERS,
  stickerCatalogue: STICKERS,
  cases: CASES.map((c) => {
    const frame = Buffer.from(yosegi.encode(c.messages, ctx));
    // 書き出す前に、自分で読み返せることを確かめる。
    const back = yosegi.decode(frame, ctx);
    if (back.length !== c.messages.length) throw new Error(c.name + ': 通数が合わない');
    return {
      name: c.name,
      note: c.note,
      messages: c.messages,
      hex: frame.toString('hex'),
      bytes: frame.length,
    };
  }),
};

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');

console.log(OUT);
