'use strict';
/**
 * Yosegi の固定バイト列を書き出す。
 *
 *   node vectors.js
 *
 * 出力: research/vectors/yosegi.json
 *
 * なぜ要るか。形式は契約で、契約は**独立した2つの読み手**が同じバイト列に同じ意味を
 * 見たときに初めて確かめられる。Kotlin と Swift が互いのコードを見ずに、この1つの
 * ファイルだけを見て一致するなら、仕様が正しいと言える。
 *
 * envelope と backup には既に formats.json があり、Yosegi だけ無かった。
 * 照合の相手がいないまま2つ目の実装を書くと、**間違いが揃ってしまう**。
 *
 * **このファイルを書き換えるのは、v2 を作るときだけ。**
 * 値が変わったら、それは形式が変わったということで、凍結を破っている。
 */
