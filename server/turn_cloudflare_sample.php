<?php
/**
 * Cloudflare Realtime TURN の資格情報。
 *
 * ===========================================================================
 *  このファイルを turn_cloudflare.php という名前で保存すると有効になります
 * ===========================================================================
 *
 * 下の2か所を、Cloudflare のダッシュボードで取得した値に置き換えてください。
 * それ以外は触らなくて大丈夫です。
 *
 *   keyId    … TURN Key ID（英数字の長い文字列）
 *   apiToken … TURN Key API Token（こちらも長い文字列。1度しか表示されません）
 *
 * ---------------------------------------------------------------------------
 * この2つが何をするのか
 * ---------------------------------------------------------------------------
 *
 * ice.php がこの2つを使って Cloudflare に問い合わせ、**数時間で切れる使い捨ての
 * ユーザー名とパスワード**を発行してもらいます。アプリが受け取るのはその使い捨ての
 * ほうだけです。
 *
 * つまり **アプリの中にこの API Token は入りません**。APK を解析されても、
 * 出てくるのは既に期限切れの資格情報だけです。固定パスワードをアプリに埋めると
 * 取り出されて他人の帯域として使われる——それを避けるための構造です。
 *
 * ---------------------------------------------------------------------------
 * 置き場所について
 * ---------------------------------------------------------------------------
 *
 * このファイルは echo.nextlab.blog 直下に置きますが、**PHP なので中身は
 * ブラウザからは見えません**（サーバーが実行してしまうため）。
 * ただし念のため、値を貼ったあとは他人に見せないでください。
 *
 * 万一漏れたと思ったら、Cloudflare のダッシュボードで API Token を
 * 作り直せば古いものはその場で無効になります。
 */

